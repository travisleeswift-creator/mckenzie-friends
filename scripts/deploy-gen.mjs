// Run from the repo root: node scripts/deploy-gen.mjs
// Embeds every file in public/ into a single Worker module and writes:
//   .deploy/worker.js          — the Worker source (gitignored)
//   .deploy/deploy-connector.js — async arrow function for the Cloudflare connector execute tool
//
// Why a Worker, not Workers Static Assets / Pages: the static-asset upload-token flow
// returned HTTP 401 through the Cloudflare connector, so we embed the built pages
// the same way as the dating-app preview Workers.
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const DIST = path.join(ROOT, "public");
const OUT = path.join(ROOT, ".deploy");
const WORKER_NAME = "mckenzie-friends";
const COMPAT_DATE = "2026-10-01";

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".mjs": "application/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".gif": "image/gif",
  ".ico": "image/x-icon",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".ttf": "font/ttf",
  ".txt": "text/plain; charset=utf-8",
  ".xml": "application/xml; charset=utf-8",
  ".map": "application/json; charset=utf-8",
  ".webmanifest": "application/manifest+json; charset=utf-8",
};

function walk(dir, base = dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? walk(full, base) : [full];
  });
}

function contentType(rel) {
  const ext = path.extname(rel).toLowerCase();
  return MIME[ext] || "application/octet-stream";
}

function parseHeaders(text) {
  const hdrs = {};
  let on = false;
  for (const line of text.split("\n")) {
    if (/^\S/.test(line)) on = line.trim() === "/*";
    else if (on && line.includes(":")) {
      const i = line.indexOf(":");
      hdrs[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
  }
  return hdrs;
}

if (!fs.existsSync(DIST)) {
  console.error("public/ missing");
  process.exit(1);
}

fs.mkdirSync(OUT, { recursive: true, mode: 0o700 });

const files = {};
let globalHeaders = {
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=()",
};

for (const f of walk(DIST)) {
  const rel = "/" + path.relative(DIST, f).split(path.sep).join("/");
  if (rel === "/_headers") {
    globalHeaders = { ...globalHeaders, ...parseHeaders(fs.readFileSync(f, "utf8")) };
    continue;
  }
  const buf = fs.readFileSync(f);
  files[rel] = { b64: buf.toString("base64"), ct: contentType(rel), size: buf.length };
}

const totalBytes = Object.values(files).reduce((s, f) => s + f.size, 0);
const workerSource = `// Auto-generated by scripts/deploy-gen.mjs — do not edit.
const FILES = ${JSON.stringify(files)};
const HDRS = ${JSON.stringify(globalHeaders)};
const cache = new Map();

function bodyOf(p) {
  if (!cache.has(p)) {
    const bin = atob(FILES[p].b64);
    const out = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    cache.set(p, out);
  }
  return cache.get(p);
}

function resolve(pathname) {
  let p = decodeURIComponent(pathname);
  if (p.length > 1 && p.endsWith("/")) p = p.slice(0, -1);
  if (p === "") p = "/";

  const candidates = [];
  if (p === "/") candidates.push("/index.html");
  else {
    candidates.push(p);
    candidates.push(p + ".html");
    candidates.push(p + "/index.html");
  }
  for (const c of candidates) if (FILES[c]) return c;
  return null;
}

function respond(key, status, method) {
  const f = FILES[key];
  const h = new Headers(HDRS);
  h.set("content-type", f.ct);
  // index.html, sw.js and the manifest must always revalidate so updates reach installed apps.
  h.set("cache-control", /\\.(png|jpe?g|webp|gif|ico|svg)$/i.test(key) ? "public, max-age=86400" : "no-cache");
  return new Response(method === "HEAD" ? null : bodyOf(key), { status, headers: h });
}

export default {
  async fetch(request) {
    if (request.method !== "GET" && request.method !== "HEAD") {
      return new Response("Method Not Allowed", { status: 405, headers: { allow: "GET, HEAD" } });
    }
    const url = new URL(request.url);
    const key = resolve(url.pathname);
    if (key) return respond(key, 200, request.method);
    return respond("/index.html", 404, request.method);
    return new Response("Not Found", { status: 404, headers: HDRS });
  },
};
`;

fs.writeFileSync(path.join(OUT, "worker.js"), workerSource, { mode: 0o600 });

const connector = `async () => {
  const name = ${JSON.stringify(WORKER_NAME)};
  const meta = {
    main_module: "worker.js",
    compatibility_date: ${JSON.stringify(COMPAT_DATE)},
    compatibility_flags: [],
  };
  const code = ${JSON.stringify(workerSource)};
  const form = new FormData();
  form.append("metadata", new Blob([JSON.stringify(meta)], { type: "application/json" }));
  form.append("worker.js", new Blob([code], { type: "application/javascript+module" }), "worker.js");
  const up = await cloudflare.request({
    method: "PUT",
    path: \`/accounts/\${accountId}/workers/scripts/\${name}\`,
    body: form,
  });
  const sd = await cloudflare.request({
    method: "POST",
    path: \`/accounts/\${accountId}/workers/scripts/\${name}/subdomain\`,
    body: { enabled: true, previews_enabled: false },
  });
  return {
    uploaded: up.success,
    id: up.result && up.result.id,
    etag: up.result && up.result.etag,
    startup_ms: up.result && up.result.startup_time_ms,
    size: up.result && up.result.size,
    subdomain: sd.result,
    url: "https://" + name + ".travisleeswift.workers.dev",
    files: ${Object.keys(files).length},
    bytes: ${totalBytes},
  };
}`;

fs.writeFileSync(path.join(OUT, "deploy-connector.js"), connector, { mode: 0o600 });

console.log(JSON.stringify({
  worker: WORKER_NAME,
  files: Object.keys(files).length,
  bytes: totalBytes,
  workerJsBytes: Buffer.byteLength(workerSource),
  paths: Object.keys(files).sort(),
  out: [".deploy/worker.js", ".deploy/deploy-connector.js"],
}, null, 2));
